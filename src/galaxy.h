/*
 * FRONTIER - the galaxy: star system records, routes and the galaxy map.
 *
 * Milestone 9 has four test systems, one per band of the galaxy. Every number
 * here (positions, owners, security, how many pirates and merchants) is a
 * placeholder to be tuned when territories and fleets are designed.
 *
 * Systems are linked by hyperspace routes (symmetric: if A lists B, B lists A).
 * Each system has one jump point per link, placed in the system's own space.
 */
#ifndef FRONTIER_GALAXY_H
#define FRONTIER_GALAXY_H

#include "common.h"

#include "galaxy_data.h"     /* GALAXY_SYSTEMS, SYS_MAX_JUMPS: generated by tools/galaxy/gen.py */

enum { BAND_CORE = 0, BAND_MID, BAND_FRONTIER, BAND_RIM, BAND_COUNT };
enum { OWN_FEDERATION = 0, OWN_INDEPENDENT, OWN_REBEL, OWN_SYNDICATE, OWN_PLAYER, OWN_NONE, OWN_VEYR, OWN_COUNT };
/* PLAYER: you took it (M14g). NONE: an empty system, no planet and no port (M16a). VEYR: theirs (M17a). */
enum { ECON_AGRICULTURAL = 0, ECON_INDUSTRIAL, ECON_MINING, ECON_MILITARY, ECON_SETTLEMENT,
       ECON_TRADE_HUB, ECON_COUNT };

typedef struct {
    const char *name;                 /* upper case */
    s16 map_x, map_y;                 /* position on the galaxy map, 0..100 */
    u8  band, owner;
    u8  security;                     /* 3 high .. 0 very low */
    u8  econ[2];                      /* [0] the station, [1] the planet */
    u8  njumps;
    u8  link[SYS_MAX_JUMPS];          /* connected system ids */
    const char *station_name, *planet_name;
    s16 planet_x, planet_y, planet_radius;
    s16 jump_x[SYS_MAX_JUMPS], jump_y[SYS_MAX_JUMPS];
    u8  planet_rgb[3];                /* lit colour of the planet */
    u8  pirates, merchants;           /* normal NPC counts (placeholders) */
    u8  base;                         /* NAV_STATION or NAV_PLANET: what launches its defence (M14g) */
    u8  hidden;                       /* in the Veyr nebula: its links are closed until the hive is found (M17a) */
} StarSystem;

/* Charts: the galaxy map only shows systems you have visited or bought a chart for. */
#define CHART_PRICE   500
#define CHART_RADIUS   40       /* map units around the current system */
int  galaxy_known(int id);
int  galaxy_empty(int id);      /* no planet and no port (M16a) */
int  galaxy_port_open(int id);  /* a port you can use: not empty and not held by the Veyr (M17a) */
void galaxy_open_nebula(int open);   /* the hive is found: the nebula's links open (M17a) */
int  galaxy_nebula_open(void);
int  galaxy_random_near(int from, int max_hops, int need_port);   /* another system within reach, or -1 */
int  galaxy_chart(void);        /* reveals the systems around here; returns how many are new */

const StarSystem *galaxy_sys(int id);
u8  *galaxy_ser(u8 *p, int load);   /* the current system, charts and course (call galaxy_enter after loading) */
void galaxy_mark_known(int id);      /* mark a system charted */
void galaxy_set_owner(int id, int owner);   /* conquest (M14g): saved with the game */
int  galaxy_owned_count(int owner);
int  galaxy_founder(int id);          /* who built it (the starting owner): what its port sells */
int  galaxy_current(void);

void galaxy_init(void);
void galaxy_enter(int id);            /* makes id the current system and loads its world */

/* Which of a system's jump points leads to `to`, or -1. */
int  galaxy_link_index(int from, int to);

int  galaxy_dist(int a, int b);       /* distance on the map */
int  galaxy_jump_fuel(int a, int b);  /* fuel units for one jump */
int  galaxy_jump_hours(int a, int b); /* game hours a jump takes */

/* The player's plotted course. */
void galaxy_set_route(int dest);      /* -1 clears */
int  galaxy_route(void);
int  galaxy_next_hop(int from, int dest);     /* next system on the shortest path, or -1 */
int  galaxy_route_fuel(int from, int dest);   /* total fuel for the whole path, or -1 */
int  galaxy_route_hops(int from, int dest);

const char *galaxy_security_name(int level);
const char *galaxy_econ_name(int econ);

/* The galaxy map screen. */
enum { GMAP_NONE = 0, GMAP_PLOTTED, GMAP_CLEARED };

void galaxy_map_open(void);
int  galaxy_map_active(void);
int  galaxy_map_update(void);         /* call each frame while active */
void galaxy_map_draw(void);

#endif
