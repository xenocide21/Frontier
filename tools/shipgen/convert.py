"""
Turns the top-down renders into PS1 sprite data.

    python3 convert.py RENDER_DIR SRC_DIR name[:size] [name[:size] ...]

size is 64 (default), 128 or 256 pixels square. Sprites are packed into PS1
texture pages (256x256 4-bit pixels each) in VRAM x 640..1023: 16 small ones a
page, 4 medium or 1 large.

For each ship: the render -> size x size (area filter on premultiplied alpha) ->
light sharpening -> 15 colours chosen for that ship (+ index 0 = transparent).
Writes src/sprites_data.c and src/sprites_data.h, plus <name>_sprite.png
previews (the exact 16-colour result) next to the renders.
"""
import sys, os
from PIL import Image, ImageFilter, ImageEnhance


def to_ps1(rgb):
    r, g, b = (min(31, (c + 4) >> 3) for c in rgb)
    v = r | (g << 5) | (b << 10)
    return v if v else 0x8000          # 0 means transparent on the PS1; keep black opaque

def convert(path, SIZE):
    im = Image.open(path).convert("RGBA")
    # premultiply, shrink, un-premultiply
    r, g, b, a = im.split()
    w = Image.new("RGBA", im.size)
    px = im.load(); wp = w.load()
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            R, G, B, A = px[x, y]
            wp[x, y] = (R * A // 255, G * A // 255, B * A // 255, A)
    small = w.resize((SIZE, SIZE), Image.BOX)
    sp = small.load()
    rgb = Image.new("RGB", (SIZE, SIZE)); rp = rgb.load()
    mask = [[False] * SIZE for _ in range(SIZE)]
    for y in range(SIZE):
        for x in range(SIZE):
            R, G, B, A = sp[x, y]
            if A >= 110:
                k = 255 / A
                rp[x, y] = (min(255, int(R * k)), min(255, int(G * k)), min(255, int(B * k)))
                mask[y][x] = True
    rgb = ImageEnhance.Contrast(rgb).enhance(1.15)
    rgb = rgb.filter(ImageFilter.UnsharpMask(radius=1.0, percent=60, threshold=2))
    # palette from the opaque pixels only
    opaque = [rgb.getpixel((x, y)) for y in range(SIZE) for x in range(SIZE) if mask[y][x]]
    strip = Image.new("RGB", (len(opaque), 1)); strip.putdata(opaque)
    q = strip.quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:45]
    colours = [tuple(pal[i * 3:i * 3 + 3]) for i in range(15)]
    # Keep the most vivid colour (engine and Veyr glows): if few pixels have it,
    # median cut drops it, so swap it in for the least used palette entry.
    def sat(c): return max(c) - min(c)
    vivid = [c for c in opaque if sat(c) > 120 and max(c) > 150]
    if vivid and min(sat(c) for c in colours) >= 0 and max(sat(c) for c in colours) < 110:
        vr = tuple(sum(c[j] for c in vivid) // len(vivid) for j in range(3))
        counts = [0] * 15
        for c in opaque:
            counts[min(range(15), key=lambda i: sum((c[j] - colours[i][j]) ** 2 for j in range(3)))] += 1
        colours[counts.index(min(counts))] = vr
    def nearest(c):
        return min(range(15), key=lambda i: sum((c[j] - colours[i][j]) ** 2 for j in range(3)))
    idx = [[0] * SIZE for _ in range(SIZE)]
    for y in range(SIZE):
        for x in range(SIZE):
            if mask[y][x]: idx[y][x] = 1 + nearest(rgb.getpixel((x, y)))
    return idx, colours

def preview(idx, colours, path, SIZE):
    im = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    for y in range(SIZE):
        for x in range(SIZE):
            if idx[y][x]: im.putpixel((x, y), (*colours[idx[y][x] - 1], 255))
    im.save(path)

PAGES = [(640, 0), (704, 0), (768, 0), (832, 0), (896, 0), (640, 256), (704, 256), (768, 256),
         (832, 256), (896, 256), (960, 256)]          # (960, 0) holds the debug font

def place(sizes):
    """Assigns each sprite a texture page and a u, v corner. Small first, then medium, then large."""
    out = [None] * len(sizes); page = 0
    for size in (64, 128, 256):
        per_row = 256 // size; slot = 0
        for k, sz in enumerate(sizes):
            if sz != size: continue
            if slot == per_row * per_row: page += 1; slot = 0
            u, v = (slot % per_row) * size, (slot // per_row) * size
            out[k] = (PAGES[page], u, v); slot += 1
        if slot: page += 1
    assert page <= len(PAGES), "out of texture pages"
    return out

def main():
    rdir, sdir, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
    names = [sp.split(":")[0] for sp in specs]
    sizes = [int(sp.split(":")[1]) if ":" in sp else 64 for sp in specs]
    spots = place(sizes)
    c_lines = ['/* Generated by tools/shipgen/convert.py from the 3D renders. Do not edit. */',
               '#include "sprite.h"', '']
    h_lines = ['/* Generated by tools/shipgen/convert.py. Do not edit. */',
               '#ifndef FRONTIER_SPRITES_DATA_H', '#define FRONTIER_SPRITES_DATA_H', '',
               f'#define SPRITE_COUNT {len(names)}', 'enum {']
    for k, n in enumerate(names):
        SIZE = sizes[k]
        idx, colours = convert(os.path.join(rdir, f"{n}_top.png"), SIZE)
        preview(idx, colours, os.path.join(rdir, f"{n}_sprite.png"), SIZE)
        h_lines.append(f'    SPR_{n.upper()} = {k},')
        data = []
        for y in range(SIZE):
            for x in range(0, SIZE, 2):
                data.append(idx[y][x] | (idx[y][x + 1] << 4))
        c_lines.append(f'static const u8 {n}_pix[{len(data)}] __attribute__((aligned(4))) = {{')
        for i in range(0, len(data), 16):
            c_lines.append('    ' + ', '.join(f'0x{v:02x}' for v in data[i:i + 16]) + ',')
        c_lines.append('};')
        clut = [0] + [to_ps1(c) for c in colours]
        c_lines.append(f'static const u16 {n}_clut[16] __attribute__((aligned(4))) = {{')
        c_lines.append('    ' + ', '.join(f'0x{v:04x}' for v in clut))
        c_lines.append('};')
        c_lines.append('')
        print(f"{n}: {SIZE}px, page {spots[k][0]}, u {spots[k][1]} v {spots[k][2]}")
    h_lines += ['};', '', 'extern const SpriteSrc sprite_srcs[SPRITE_COUNT];', '', '#endif', '']
    c_lines.append('const SpriteSrc sprite_srcs[SPRITE_COUNT] = {')
    for k, n in enumerate(names):
        (px, py), u, v = spots[k]
        c_lines.append(f'    {{ {n}_pix, {n}_clut, "{n.upper()}", {sizes[k]}, {px}, {py}, {u}, {v} }},')
    c_lines.append('};')
    open(os.path.join(sdir, "sprites_data.c"), "w").write("\n".join(c_lines) + "\n")
    open(os.path.join(sdir, "sprites_data.h"), "w").write("\n".join(h_lines))
    print("wrote", len(names), "sprites")

main()
