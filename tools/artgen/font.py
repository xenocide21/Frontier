"""Builds the three font atlases (small 8x9, medium 16x18, large 24x26 cells,
4-bit, anti-aliased, with a baked drop shadow) -> src/font_data.c + a preview PNG."""
import sys
from PIL import Image, ImageDraw
from glyphs import GLYPHS, interp
SS = 8
SIZES = dict(   # cell w, h, stroke, x snap, y snap, shadow offset, columns
    small =(8, 9, 1, [0,1,3,5,6], [0,1,2,3,5,6,7], 1, 16),
    medium=(16, 18, 2, [0,3,6,9,12], [0,3,5,7,9,11,14], 1, 15),
    large =(24, 26, 3, [0,4,9,14,18], [0,4,7,10,14,17,21], 2, 10))

def coverage(ch, w, h, sw, xs, ys):
    im = Image.new("L", (w * SS, h * SS), 0); d = ImageDraw.Draw(im)
    for line in GLYPHS[ch]:
        pts = [((interp(xs, x) + sw / 2) * SS, (interp(ys, y) + sw / 2) * SS) for x, y in line]
        r = sw * SS / 2
        if len(pts) > 1 and pts[0] != pts[-1] or len(pts) > 2:
            d.line(pts, fill=255, width=int(sw * SS), joint="curve")
        for (x, y) in pts:
            d.ellipse([x - r, y - r, x + r - 1, y + r - 1], fill=255)
    return im.resize((w, h), Image.BOX)

def atlas(name):
    w, h, sw, xs, ys, sh, cols = SIZES[name]
    rows = (64 + cols - 1) // cols
    out = Image.new("P", (cols * w, rows * h), 0)
    for i in range(64):
        cov = coverage(chr(32 + i), w, h, sw, xs, ys)
        px = cov.load()
        for y in range(h):
            for x in range(w):
                c = px[x, y] / 255.0
                lvl = round(c * 14)
                idx = lvl + 1 if lvl > 0 else 0
                if idx == 0 and x >= sh and y >= sh and px[x - sh, y - sh] > 110: idx = 1
                elif idx in (2, 3, 4) and x >= sh and y >= sh and px[x - sh, y - sh] > 110: idx = max(idx, 2)
                out.putpixel(((i % cols) * w + x, (i // cols) * h + y), idx)
    return out

def pack(im, wpad=None):
    w, h = im.size; wpad = wpad or (w + 3) // 4 * 4
    words = []
    for y in range(h):
        for x in range(0, wpad, 4):
            v = 0
            for k in range(4):
                if x + k < w: v |= im.getpixel((x + k, y)) << (4 * k)
            words.append(v)
    return wpad // 4, h, words

def clut():
    c = [0, 0x8000]                      # clear, shadow (black with the mask bit: opaque)
    for i in range(1, 15):
        v = round(31 * (i / 14) ** 0.8); c.append(v | v << 5 | v << 10)
    return c

def emit(f, name, im):
    w, h, words = pack(im)
    f.write(f"const u16 {name}[] __attribute__((aligned(4))) = {{ /* {w*4}x{h} */\n")
    for i in range(0, len(words), 16):
        f.write("    " + ",".join("0x%04x" % v for v in words[i:i+16]) + ",\n")
    f.write("};\n")
    return w, h

if __name__ == "__main__":
    out, prev = sys.argv[1], sys.argv[2]
    ims = {n: atlas(n) for n in SIZES}
    with open(out, "w") as f:
        f.write('/* Generated by tools/artgen/font.py: the FRONTIER typeface in three sizes. */\n#include "common.h"\n\n')
        for n in SIZES:
            w, h = emit(f, f"font_{n}_pix", ims[n]); f.write(f"const u16 font_{n}_wh[2] = {{ {w}, {h} }};\n\n")
        f.write("const u16 font_clut[16] __attribute__((aligned(4))) = { " + ", ".join("0x%04x" % v for v in clut()) + " };\n\n")
        # A soft round glow, 64x64: drawn additively (every colour has the mask bit) for
        # engines, shots, explosions and suns.
        g = Image.new("P", (64, 64), 0)
        for y in range(64):
            for x in range(64):
                d = ((x - 31.5) ** 2 + (y - 31.5) ** 2) ** 0.5 / 31.5
                v = max(0.0, 1 - d) ** 1.8
                g.putpixel((x, y), min(15, round(v * 15)))
        emit(f, "glow_pix", g)
        gc = [0] + [0x8000 | (round(31 * i / 15) * 0x421) for i in range(1, 16)]
        f.write("const u16 glow_clut[16] __attribute__((aligned(4))) = { " + ", ".join("0x%04x" % v for v in gc) + " };\n")
    pal = []
    for v in clut(): pal += [(v & 31) * 8, (v >> 5 & 31) * 8, (v >> 10 & 31) * 8]
    pal[0:3] = [30, 40, 90]
    sheet = Image.new("RGB", (490, 330), (30, 40, 90)); y = 0
    for n in SIZES:
        im = ims[n].copy(); im.putpalette(pal + [0] * (768 - 48)); sheet.paste(im.convert("RGB"), (0, y)); y += im.size[1] + 6
    sheet.resize((980, 660), Image.NEAREST).save(prev)
