def interp(table, g):
    """Grid coordinate (may be fractional or past the ends) to pixels via a snap table."""
    n = len(table) - 1
    i = max(0, min(n - 1, int(g // 1)))
    return table[i] + (g - i) * (table[i + 1] - table[i])
